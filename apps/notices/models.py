from django.db import models
from django.conf import settings

from apps.core.models import TimeStampedModel, SoftDeleteModel
from apps.core.utils import notice_attachment_path
from apps.core.constants import NOTICE_PRIORITY_LOW


class Notice(TimeStampedModel, SoftDeleteModel):
    """Announcement with AI summary + targeted audience."""
    title = models.CharField(max_length=200)
    content = models.TextField()

    # AI-generated
    ai_summary = models.TextField(
        blank=True,
        help_text="2-line summary generated by LLM."
    )

    # Global AI priority
    ai_priority = models.CharField(
        max_length=10,
        default='low',
        choices=[
            ('low', 'Low'),
            ('medium', 'Medium'),
            ('high', 'High'),
            ('critical', 'Critical'),
        ],
        help_text="Global priority from AI"
    )

    # AI-extracted keywords for per-student relevance matching
    ai_keywords = models.JSONField(
        default=list,
        blank=True,
        help_text="Extracted keywords for relevance matching"
    )

    # Per-audience relevance indicators
    relevant_to_attendance = models.BooleanField(default=False)
    relevant_to_fees = models.BooleanField(default=False)
    relevant_to_exams = models.BooleanField(default=False)
    relevant_to_hostel = models.BooleanField(default=False)
    relevant_to_placement = models.BooleanField(default=False)

    # Notice expiry
    expires_at = models.DateTimeField(
        null=True,
        blank=True
    )

    # Targeting: JSON of {
    # 'department': 'CSE',
    # 'batch_year': '2023',
    # 'hostel_block': 'A'
    # }
    target_audience = models.JSONField(
        default=dict,
        blank=True
    )

    attachment = models.FileField(
        upload_to=notice_attachment_path,
        null=True,
        blank=True
    )

    posted_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='posted_notices'
    )

    is_published = models.BooleanField(default=True)

    class Meta:
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['-created_at', 'is_published']),
        ]

    def total_targeted(self):
        """How many students does this notice target?"""
        from apps.accounts.models import User

        qs = User.objects.filter(role='student')
        aud = self.target_audience or {}

        if aud.get('department'):
            qs = qs.filter(department=aud['department'])

        if aud.get('batch_year'):
            qs = qs.filter(batch_year=aud['batch_year'])

        if aud.get('hostel_block'):
            qs = qs.filter(hostel_block=aud['hostel_block'])

        return qs.count()

    def read_count(self):
        return self.read_status.count()

    def read_percentage(self):
        total = self.total_targeted()

        if total == 0:
            return 0.0

        return round(
            (self.read_count() / total) * 100,
            1
        )

    def __str__(self):
        return f"{self.title} ({self.ai_priority})"


class NoticeReadStatus(models.Model):
    """Tracks which student read which notice."""
    notice = models.ForeignKey(
        Notice,
        on_delete=models.CASCADE,
        related_name='read_status'
    )

    student = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='notice_reads'
    )

    read_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ('notice', 'student')
        indexes = [
            models.Index(fields=['notice', 'student']),
        ]

    def __str__(self):
        return f"{self.student.username} read {self.notice.id}"